import type { BOQ } from "@/types/boq";

const createTotals = (subtotal: number, discountPercentage = 0, taxRate = 5) => {
  const discountAmount = parseFloat(((subtotal * discountPercentage) / 100).toFixed(2));
  const taxableAmount = parseFloat((subtotal - discountAmount).toFixed(2));
  const taxAmount = parseFloat(((taxableAmount * taxRate) / 100).toFixed(2));
  const grandTotal = parseFloat((taxableAmount + taxAmount).toFixed(2));
  return {
    directCost: subtotal,
    landedCost: subtotal,
    grossProfit: 0,
    grossMarginPercentage: 0,
    subtotal,
    discountPercentage,
    discountAmount,
    taxableAmount,
    taxAmount,
    grandTotal,
  };
};

