/**
 * `en` is declared `as const` so its exact key structure is preserved (and
 * so translate.ts's DotPaths<> can walk it) — but that also makes every
 * LEAF a string LITERAL type. Without widening, ar.ts (whose values are
 * necessarily different literal strings) could never type-check against
 * `Dictionary` at all. `Widen<T>` keeps every key required in the same
 * shape while relaxing only the leaf value type to plain `string`, so
 * ar.ts still gets full missing/extra-key checking with real content.
 */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };
export type Dictionary = Widen<typeof en>;
